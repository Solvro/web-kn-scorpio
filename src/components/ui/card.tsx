import { cn } from "cn";
import * as React from "react";

function Card({
  className,
  size = "default",
  ...props
}: React.ComponentProps<"div"> & { size?: "default" | "sm" }) {
  return (
    <div
      data-slot="card"
      data-size={size}
      className={cn(
        "group/card text-card-foreground ring-foreground/10 bg-card/60 ring-border/70 hover:ring-primary/40 flex flex-col overflow-hidden rounded-lg p-4 text-sm shadow-xs ring transition-all [--card-spacing:--spacing(6)] hover:ring-2 has-[>img:first-child]:pt-0 data-[size=sm]:[--card-spacing:--spacing(4)] *:[img:first-child]:rounded-t-xl *:[img:last-child]:rounded-b-xl",
        className,
      )}
      {...props}
    />
  );
}

